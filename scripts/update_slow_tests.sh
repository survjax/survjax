#!/usr/bin/env bash
# Regenerate tests/slow_tests.txt from measured durations.
# Usage: scripts/update_slow_tests.sh [--through A<N>]   (default: all baseline tests plus committed features)
#
# Runs the implementer tests and the spec tests once per dtype mode with
# --durations=0, sums setup+call+teardown per test, takes the slower mode, and
# lists every test at or above SLOW_THRESHOLD seconds (default 1.0). Tests in
# the list carry the `slow` marker (tests/conftest.py); the fast gate
# (`scripts/check.sh --fast`, `scripts/run_tests.sh --fast`) deselects them.
# Re-run after adding expensive tests; stale entries are harmless.
set -euo pipefail

through=""
while [ $# -gt 0 ]; do
  case "$1" in
    --through)
      [[ "${2:-}" =~ ^A[0-9]+$ ]] || { echo "--through requires A<N>" >&2; exit 2; }
      through="$2"; shift 2 ;;
    *) echo "usage: scripts/update_slow_tests.sh [--through A<N>]" >&2; exit 2 ;;
  esac
done
threshold="${SLOW_THRESHOLD:-1.0}"
workers="${PYTEST_WORKERS:-8}"

cd "$(git rev-parse --show-toplevel)"
SPEC_FEATURES="$(sed 's/#.*//; s/^[[:space:]]*//; s/[[:space:]]*$//; /^[[:space:]]*$/d' scripts/spec-features.txt | paste -sd, -)"
export SPEC_FEATURES
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [ -z "${SURVJAX_WHEEL:-}" ]; then
  uv build --wheel -q -o "$tmp/wheel"
  SURVJAX_WHEEL="$(ls "$tmp"/wheel/*.whl)"
  export SURVJAX_WHEEL
fi

for x64 in 1 0; do
  echo "measuring, JAX_ENABLE_X64=$x64"
  JAX_ENABLE_X64=$x64 uv run --group test pytest -q -n "$workers" -p no:cacheprovider \
    --ignore=tests/spec --durations=0 >"$tmp/impl-$x64.txt" || true
  JAX_ENABLE_X64=$x64 SPEC_THROUGH="$through" uv run --group test pytest tests/spec -q \
    -n "$workers" -p no:cacheprovider --durations=0 >"$tmp/spec-$x64.txt" || true
done

uv run python - "$threshold" "$tmp"/*.txt >tests/slow_tests.txt <<'PY'
import collections
import re
import sys

threshold = float(sys.argv[1])
slowest: dict[str, float] = collections.defaultdict(float)
for name in sys.argv[2:]:
    per_test: dict[str, float] = collections.defaultdict(float)
    with open(name) as log:
        for line in log:
            match = re.match(r"([0-9.]+)s (setup|call|teardown)\s+(\S+)", line)
            if match:
                per_test[match[3]] += float(match[1])
    for test, seconds in per_test.items():
        slowest[test] = max(slowest[test], seconds)
slow = sorted(test for test, seconds in slowest.items() if seconds >= threshold)
total = sum(slowest.values())
share = sum(slowest[test] for test in slow)
print("# Tests marked `slow` (tests/conftest.py); the fast gate deselects them.")
print("# Generated by scripts/update_slow_tests.sh; do not edit by hand.")
print(f"# threshold {threshold}s (setup+call+teardown, slower dtype mode, local run):")
print(f"# {len(slow)} tests, {share:.0f}s of {total:.0f}s summed test time")
for test in slow:
    print(test)
print(f"{len(slow)} slow tests written to tests/slow_tests.txt", file=sys.stderr)
PY
